import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const readmePath = join(scriptDirectory, "README.md");
const startMarker = "<!-- contributors:start -->";
const endMarker = "<!-- contributors:end -->";

function githubRepository() {
  const remote = execFileSync("git", ["remote", "get-url", "origin"], {
    cwd: scriptDirectory,
    encoding: "utf8",
  }).trim();
  const match = remote.match(/github\.com[/:]([^/]+)\/(.+?)(?:\.git)?$/);

  if (!match) {
    throw new Error(`Cannot determine a GitHub repository from origin: ${remote}`);
  }

  return `${match[1]}/${match[2]}`;
}

async function github(path) {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "plugins-contributor-table",
    "X-GitHub-Api-Version": "2022-11-28",
  };

  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }

  const response = await fetch(`https://api.github.com/${path}`, { headers });
  if (!response.ok) {
    throw new Error(`GitHub API returned ${response.status}: ${await response.text()}`);
  }

  return response.json();
}

async function contributors(repository) {
  const results = [];

  for (let page = 1; ; page += 1) {
    const batch = await github(
      `repos/${repository}/contributors?anon=1&per_page=100&page=${page}`,
    );
    results.push(...batch.filter((contributor) => contributor.type !== "Bot"));

    if (batch.length < 100) break;
  }

  return Promise.all(
    results.map(async (contributor) => {
      if (!contributor.login) return contributor;
      const profile = await github(`users/${contributor.login}`);
      return { ...contributor, name: profile.name || contributor.login };
    }),
  );
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function contributorCell(contributor) {
  const name = escapeHtml(contributor.name || "Anonymous contributor");
  const login = contributor.login ? `@${escapeHtml(contributor.login)}` : name;
  const image = escapeHtml(contributor.avatar_url);
  const profile = escapeHtml(contributor.html_url || `https://github.com`);

  return `    <td align="center"><a href="${profile}"><img src="${image}" width="80px" alt="${name}" /><br /><sub><b>${name}</b></sub><br /><sub>${login}</sub></a></td>`;
}

function contributorTable(items) {
  const rows = [];
  for (let index = 0; index < items.length; index += 6) {
    rows.push(
      "  <tr>",
      ...items.slice(index, index + 6).map(contributorCell),
      "  </tr>",
    );
  }

  return [
    startMarker,
    "<!-- Generated by update-contributors.mjs. Do not edit by hand. -->",
    "<table>",
    ...rows,
    "</table>",
    endMarker,
  ].join("\n");
}

const readme = await readFile(readmePath, "utf8");
const markerPattern = new RegExp(`${startMarker}[\\s\\S]*?${endMarker}`);
if (!markerPattern.test(readme)) {
  throw new Error(`Contributor markers are missing from ${readmePath}`);
}

const items = await contributors(githubRepository());
await writeFile(readmePath, readme.replace(markerPattern, contributorTable(items)));
console.log(`Updated ${items.length} contributors in ${readmePath}`);